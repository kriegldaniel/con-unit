package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// packMarkerPrefix keys the packs that a footnote lists in the marker set of
// RenderTable, next to the single-letter footnote markers.
const packMarkerPrefix = "pack:"

// Output file names, fixed by the shared contract (addendum 11).
const (
	resultsFileName = "rq1_results.json"
	tableFileName   = "table_rq1_detection.tex"
)

// defaultConUnitPack is the pack a ConUnit row runs with unless the oracle
// says otherwise. A different pack gets a footnote marker in the table.
const defaultConUnitPack = "cis"

// Matrix symbols, one per classification. The symbol alone carries the
// meaning, so the table reads in grayscale: a filled circle is a detection, an
// open circle a silent clean control, a cross a defect that an in-scope tool
// did not detect, a triangle a flagged clean control.
const (
	symbolTP         = `$\bullet$`
	symbolTN         = `$\circ$`
	symbolFN         = `$\times$`
	symbolFP         = `$\triangle$`
	symbolOutOfScope = `\textendash{}`
	symbolUnverified = `?`
	symbolNotRun     = `n/r`
	symbolToolError  = `err`
	symbolNotEval    = `n/e`
	symbolUnknown    = `??`
)

// classSymbol is the matrix symbol of a class.
func classSymbol(class string) string {
	switch class {
	case ClassTP:
		return symbolTP
	case ClassTN:
		return symbolTN
	case ClassFN:
		return symbolFN
	case ClassFP:
		return symbolFP
	case ClassOutOfScope:
		return symbolOutOfScope
	case ClassNotRun:
		return symbolNotRun
	case ClassToolError:
		return symbolToolError
	case ClassUnverified:
		return symbolUnverified
	case ClassNotEvaluated:
		return symbolNotEval
	}
	return symbolUnknown
}

// tone is the light shade of a cell. It only repeats what the symbol says:
// correct, wrong, or not scored.
type tone int

const (
	toneNeutral tone = iota
	toneGood
	toneBad
)

// toneColor mixes the palette colors of the figures with white.
var toneColor = map[tone]string{
	toneNeutral: "cuUnver!20",
	toneGood:    "cuPass!22",
	toneBad:     "cuFail!24",
}

// matrixPalette makes the file compile on its own. \providecolor never
// redefines a color the paper already set.
const matrixPalette = "\\providecolor{cuPass}{HTML}{009E73}\n" +
	"\\providecolor{cuFail}{HTML}{D55E00}\n" +
	"\\providecolor{cuUnver}{HTML}{7F7F7F}\n"

// classTone says whether a class is a correct outcome (TP, TN), a wrong one
// (FN, FP, tool error) or one that is not scored (out of scope, not run,
// UNVERIFIED).
func classTone(class string) tone {
	switch class {
	case ClassTP, ClassTN:
		return toneGood
	case ClassFN, ClassFP, ClassToolError:
		return toneBad
	}
	return toneNeutral
}

// cellTone is the shade of a cell that holds several classes: wrong if any
// outcome is wrong, correct only if all are, not scored otherwise.
func cellTone(classes []string) tone {
	good := 0
	for _, c := range classes {
		switch classTone(c) {
		case toneBad:
			return toneBad
		case toneGood:
			good++
		}
	}
	if good == len(classes) && good > 0 {
		return toneGood
	}
	return toneNeutral
}

// shade colors a cell. The shade is a light mix, so black symbols stay legible.
func shade(t tone, content string) string {
	return "\\cellcolor{" + toneColor[t] + "}" + content
}

// WriteResults writes rq1_results.json and table_rq1_detection.tex into outDir.
func WriteResults(o *Oracle, res *Results, outDir string) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	if err := writeJSON(filepath.Join(outDir, resultsFileName), res); err != nil {
		return fmt.Errorf("writing %s: %w", resultsFileName, err)
	}
	table := RenderTable(o, res)
	if err := os.WriteFile(filepath.Join(outDir, tableFileName), []byte(table), 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", tableFileName, err)
	}
	return nil
}

// RenderTable builds the LaTeX detection matrix from the results. Properties
// are rows and every tool is a column group with two columns: D lists the
// outcome on each defect case, C the outcome on the clean control. Each case
// has one symbol, and a light shade repeats whether the outcome is correct.
// All text is generated from the data. There is no analysis prose.
func RenderTable(o *Oracle, res *Results) string {
	byID := map[string]CaseResult{}
	for _, c := range res.Cases {
		byID[c.ID] = c
	}
	tools := o.Tools

	markers := map[string]bool{}
	var sb strings.Builder
	sb.WriteString("% Generated by tools/rq1 from rq1_results.json. Do not edit by hand.\n")
	sb.WriteString("% Requires: \\usepackage[table]{xcolor} (colortbl, for \\cellcolor) and booktabs.\n")
	sb.WriteString("% Single-column table environment at its natural width; no scaling.\n")
	sb.WriteString(matrixPalette)
	sb.WriteString("\\begin{table}[t]\n\\centering\n")
	sb.WriteString("\\caption{Detection outcome on the defect-seeded corpus, one symbol per case (D: defect cases, C: clean control). ")
	sb.WriteString(symbolTP + " TP, " + symbolFN + " FN (defect not detected), " + symbolFP + " FP (clean control flagged), " + symbolTN + " TN, ")
	sb.WriteString(symbolOutOfScope + " out of scope, " + symbolUnverified + " UNVERIFIED, " + symbolNotEval + " not evaluated by the tool, " + symbolNotRun + " not run, " + symbolToolError + " no usable verdict. ")
	sb.WriteString("Shade: green correct, vermilion wrong, gray not scored.}\n")
	sb.WriteString("\\label{tab:rq1_detection}\n")
	sb.WriteString("{\\scriptsize\n\\setlength{\\tabcolsep}{2.2pt}\n")
	// A small gap between the column groups of the tools breaks the shading.
	groups := make([]string, len(tools))
	for i := range tools {
		groups[i] = "cc"
	}
	sb.WriteString("\\begin{tabular}{l" + strings.Join(groups, `@{\hspace{3pt}}`) + "}\n\\toprule\n")
	for _, t := range tools {
		sb.WriteString(" & \\multicolumn{2}{c}{\\textbf{" + latexEscape(displayTool(t)) + "}}")
	}
	sb.WriteString(" \\\\\n")
	for i := range tools {
		sb.WriteString(fmt.Sprintf("\\cmidrule(lr){%d-%d}", 2+2*i, 3+2*i))
	}
	sb.WriteString("\n\\textbf{Property}")
	for range tools {
		sb.WriteString(" & \\textbf{D} & \\textbf{C}")
	}
	sb.WriteString(" \\\\\n\\midrule\n")

	for _, prop := range o.PropertyOrder() {
		sb.WriteString("\\texttt{" + latexEscape(prop) + "}")
		for _, t := range tools {
			sb.WriteString(" & " + toolCells(o, byID, prop, t, markers))
		}
		sb.WriteString(" \\\\\n")
	}

	sb.WriteString("\\midrule\n")
	rows := []struct {
		label string
		cell  func(ToolSummary) string
	}{
		{"Recall (in scope)", func(s ToolSummary) string { return metricCell(s, s.Recall) }},
		{"False positives", func(s ToolSummary) string { return metricCell(s, s.FalsePositiveRate) }},
		{"Out of scope (cases)", func(s ToolSummary) string {
			if s.Status == "NOT_RUN" {
				return "n/r"
			}
			return fmt.Sprintf("%d/%d", s.Counts[ClassOutOfScope], len(res.Cases))
		}},
	}
	for _, r := range rows {
		sb.WriteString(r.label)
		for _, t := range tools {
			sb.WriteString(" & \\multicolumn{2}{c}{" + r.cell(res.Summary[t]) + "}")
		}
		sb.WriteString(" \\\\\n")
	}
	sb.WriteString("\\bottomrule\n\\end{tabular}}\n")

	sb.WriteString("\\par\\smallskip\n{\\footnotesize\n")
	if markers["a"] {
		sb.WriteString("\\textsuperscript{a} Rule disabled by default, enabled explicitly with tool flags. \\\\\n")
	}
	if markers["b"] {
		var packs []string
		for key := range markers {
			if strings.HasPrefix(key, packMarkerPrefix) {
				packs = append(packs, strings.TrimPrefix(key, packMarkerPrefix))
			}
		}
		sort.Strings(packs)
		sb.WriteString("\\textsuperscript{b} Run with a pack other than the hardening profile (" + latexEscape(strings.Join(packs, ", ")) + "). \\\\\n")
	}
	sb.WriteString("Versions: ")
	var versions []string
	for _, t := range tools {
		info := res.Tools[t]
		v := info.Version
		switch {
		case !info.Available:
			v = "not run"
		case v == "":
			v = "version unknown"
		}
		versions = append(versions, displayTool(t)+" "+latexEscape(v))
	}
	sb.WriteString(strings.Join(versions, "; ") + ".\n")
	if res.Engine.Version != "" {
		sb.WriteString("\\\\ Build engine: " + latexEscape(res.Engine.Version) + ".\n")
	}
	sb.WriteString("}\n\\end{table}\n")
	return sb.String()
}

// toolCells renders the two cells of one tool for one property: the defect
// cell with one symbol per defect case in corpus order, and the control cell.
// A tool that is out of scope or was not run for the whole property gets one
// cell spanning both columns. A case without a result is ??, never silent.
func toolCells(o *Oracle, byID map[string]CaseResult, prop, tool string, markers map[string]bool) string {
	var defects []string
	control := ""
	for _, c := range o.CasesOf(prop) {
		class := ""
		if cr, ok := byID[c.ID]; ok {
			class = cr.Tools[tool].Class
		}
		if c.DefectPresent {
			defects = append(defects, class)
		} else {
			control = class
		}
	}
	all := append(append([]string{}, defects...), control)
	if allEqual(all) && (all[0] == ClassOutOfScope || all[0] == ClassNotRun) {
		return "\\multicolumn{2}{c}{" + shade(classTone(all[0]), classSymbol(all[0])) + "}"
	}

	symbols := make([]string, len(defects))
	for i, d := range defects {
		symbols[i] = classSymbol(d)
	}
	defectCell := strings.Join(symbols, `\,`)
	scope := o.Properties[prop].Tools[tool]
	if scope.InScope && len(scope.Args) > 0 {
		defectCell += "\\textsuperscript{a}"
		markers["a"] = true
	}
	if scope.InScope && tool == ToolConUnit && scope.Pack != "" && scope.Pack != defaultConUnitPack {
		defectCell += "\\textsuperscript{b}"
		markers["b"] = true
		markers[packMarkerPrefix+scope.Pack] = true
	}
	return shade(cellTone(defects), defectCell) + " & " + shade(classTone(control), classSymbol(control))
}

func metricCell(s ToolSummary, m Metric) string {
	if s.Status == "NOT_RUN" {
		return "n/r"
	}
	if m.Denominator == 0 {
		return "n/a"
	}
	return fmt.Sprintf("%d/%d", m.Numerator, m.Denominator)
}

func allEqual(items []string) bool {
	for _, it := range items {
		if it != items[0] {
			return false
		}
	}
	return len(items) > 0
}

func displayTool(t string) string {
	switch t {
	case ToolConUnit:
		return "ConUnit"
	case ToolHadolint:
		return "Hadolint"
	case ToolTrivy:
		return "Trivy"
	case ToolCST:
		return "CST"
	case ToolDockle:
		return "Dockle"
	}
	return t
}

// latexEscape escapes the characters that are special in LaTeX text.
func latexEscape(s string) string {
	var sb strings.Builder
	for _, r := range s {
		switch r {
		case '\\':
			sb.WriteString(`\textbackslash{}`)
		case '&', '%', '$', '#', '_', '{', '}':
			sb.WriteRune('\\')
			sb.WriteRune(r)
		case '~':
			sb.WriteString(`\textasciitilde{}`)
		case '^':
			sb.WriteString(`\textasciicircum{}`)
		default:
			sb.WriteRune(r)
		}
	}
	return sb.String()
}
