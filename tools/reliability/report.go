// Output file names (docs/INTERFACE_V2.md section 6).
const (
	jsonFile   = "reliability.json"
	tableFile  = "table_reliability.tex"
	macrosFile = "macros_reliability.tex"
)

// tableLabel is the label of the table, which belongs to the supplement.
const tableLabel = "tab:reliability"

type macro struct {
	name    string
	value   string
	comment string
}

// reliabilityMacros returns the macros in the order of docs/INTERFACE_V2.md
// section 6, with ConUnitRelPairs after the number of images and the two Tier 3
// macros after the flip counts. ConUnitRelPairs and the Tier 3 pairs are
// additions to the contract (see amendment A7).
func reliabilityMacros(r *Report) []macro {
	na := tex.NotAvailable
	flips := func(n int) string {
		// A flip count over no pair would read as perfect stability.
		if r.Pairs == 0 {
			return na
		}
		return strconv.Itoa(n)
	}
	// The Tier 3 numbers restate the same definition over the Tier 3 rules, the
	// checks that depend on the observation window.
	var tier3Pairs, tier3Flipped = na, na
	if r.RepeatDetail != nil && r.RepeatDetail.TierThreePairs > 0 {
		tier3Pairs = strconv.Itoa(r.RepeatDetail.TierThreePairs)
		tier3Flipped = strconv.Itoa(r.RepeatDetail.TierThreeFlippedPairs)
	}
	windowChanged := na
	if r.WindowChanged != nil {
		windowChanged = strconv.Itoa(*r.WindowChanged)
	}
	orNA := func(s string) string {
		if s == "" {
			return na
		}
		return s
	}
	return []macro{
		{"ConUnitRelRepeats", strconv.Itoa(r.Repeats),
			"Number of repeated runs that are compared."},
		{"ConUnitRelImages", strconv.Itoa(r.Images),
			"Images that completed in every repeat."},
		{"ConUnitRelPairs", strconv.Itoa(r.Pairs),
			"Pairs of check and image that have a PASS or FAIL verdict in every repeat. This is the denominator of the flip counts. A pair with an UNVERIFIED verdict in any repeat is not counted here and is listed in pairs_unverified_in_some_repeat of reliability.json."},
		{"ConUnitRelFlippedImages", flips(r.FlippedImages),
			"Images with at least one flipped pair, over the pairs of ConUnitRelPairs."},
		{"ConUnitRelFlippedChecks", flips(r.FlippedChecks),
			"Pairs of check and image whose PASS or FAIL verdict is not the same in every repeat, counted over exactly the pairs of ConUnitRelPairs."},
		{"ConUnitRelPairsTierThree", tier3Pairs,
			"The pairs of ConUnitRelPairs that belong to the Tier 3 rules (EXEC), with a PASS or FAIL verdict in every repeat. This is the denominator of the stability rule of the analysis plan. n/a when there is no such pair."},
		{"ConUnitRelFlippedChecksTierThree", tier3Flipped,
			"Pairs of ConUnitRelFlippedChecks that belong to the Tier 3 rules, counted over exactly the pairs of ConUnitRelPairsTierThree. n/a when there is no such pair."},
		{"ConUnitRelWindowChanged", windowChanged,
			"Pairs of check and image whose verdict (PASS, FAIL or UNVERIFIED) is not the same at every window."},
		{"ConUnitRelWindowShort", orNA(r.WindowShortS),
			"The shortest window in seconds, read from the run metadata. A plain number without a unit."},
		{"ConUnitRelWindowMid", orNA(r.WindowMidS),
			"The middle window in seconds, defined for exactly three windows. A plain number without a unit."},
		{"ConUnitRelWindowLong", orNA(r.WindowLongS),
			"The longest window in seconds, read from the run metadata. A plain number without a unit."},
	}
}

// RenderMacros renders macros_reliability.tex.
func RenderMacros(r *Report) string {
	var sb strings.Builder
	sb.WriteString("% Generated by tools/reliability from reliability.json. Do not edit by hand.\n")
	sb.WriteString("% Macro names contain letters only. Counts have no unit. The window macros are plain numbers in seconds without a unit, the text adds the unit.\n")
	sb.WriteString("% A value for which no data exists prints n/a.\n")
	if r.Incomplete() {
		sb.WriteString("% WARNING: some image could not be compared because it did not complete in every run. See excluded_images in reliability.json.\n")
	}
	for _, m := range reliabilityMacros(r) {
		fmt.Fprintf(&sb, "\n%% %s\n\\newcommand{\\%s}{%s}\n", m.comment, m.name, m.value)
	}
	return sb.String()
}

// windowList writes the windows as "3, 10 and 30 s" for the caption, empty when
// they are unknown.
func windowList(ms []int64) string {
	if len(ms) == 0 {
		return ""
	}
	sorted := append([]int64(nil), ms...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i] < sorted[j] })
	parts := make([]string, len(sorted))
	for i, m := range sorted {
		if m <= 0 {
			return ""
		}
		parts[i] = seconds(m)
	}
	if len(parts) == 1 {
		return parts[0] + " s"
	}
	return strings.Join(parts[:len(parts)-1], ", ") + " and " + parts[len(parts)-1] + " s"
}

// tableRow is one row of the table: a label and the four counts.
type tableRow struct {
	label                      string
	pairs, flipped, unverified int
	windowPairs, windowChanged int
}

func (t *tableRow) add(c CheckStat) {
	t.pairs += c.Pairs
	t.flipped += c.Flipped
	t.unverified += c.UnverifiedInSomeRepeat
	t.windowPairs += c.WindowPairs
	t.windowChanged += c.WindowChanged
}

// tableRows groups the checks: every Tier 3 check has its own row, the checks
// of the other tiers are summed per tier.
func tableRows(checks []CheckStat) []tableRow {
	var rows []tableRow
	byTier := map[int]*tableRow{}
	var tierOrder []int
	counts := map[int]int{}
	for _, c := range checks {
		if c.TierThree() {
			row := tableRow{label: tex.Texttt(c.Rule)}
			row.add(c)
			rows = append(rows, row)
			continue
		}
		row, ok := byTier[c.Tier]
		if !ok {
			row = &tableRow{}
			byTier[c.Tier] = row
			tierOrder = append(tierOrder, c.Tier)
		}
		row.add(c)
		counts[c.Tier]++
	}
	for _, tier := range tierOrder {
		row := byTier[tier]
		noun := "checks"
		if counts[tier] == 1 {
			noun = "check"
		}
		row.label = fmt.Sprintf("Tier %d, %d %s", tier, counts[tier], noun)
		rows = append(rows, *row)
	}
	return rows
}

// RenderTable renders table_reliability.tex with the label tab:reliability.
func RenderTable(r *Report) string {
	na := tex.NotAvailable
	var sb strings.Builder

	windows := ""
	if r.WindowDetail != nil {
		windows = windowList(r.WindowDetail.WindowsMs)
	}
	repeatWindow := "an unknown window"
	if r.RepeatDetail != nil && r.RepeatDetail.WindowMs > 0 {
		repeatWindow = "a window of " + seconds(r.RepeatDetail.WindowMs) + " s"
	}
	caption := fmt.Sprintf("Stability of the verdicts on %d images. "+
		"Repeats: %d runs with %s. A pair is one check on one image. "+
		"Pairs counts the pairs with a PASS or FAIL verdict in every repeat, Flipped those among them whose verdict differs between repeats, "+
		"and Unverified the pairs with an UNVERIFIED verdict in some repeat, which are in neither number. ",
		r.Images, r.Repeats, repeatWindow)
	if windows != "" {
		caption += fmt.Sprintf("Window: pairs whose verdict is not the same at the windows %s, over the pairs compared.", windows)
	} else {
		caption += "Window: no runs at other windows were given."
	}

	sb.WriteString("% Generated by tools/reliability from reliability.json. Do not edit by hand.\n")
	sb.WriteString("\\begin{table}[t]\n\\centering\n\\small\n")
	fmt.Fprintf(&sb, "\\caption{%s}\n\\label{%s}\n", tex.Escape(caption), tableLabel)
	sb.WriteString("\\begin{tabular}{lrrrr}\n\\toprule\n")
	sb.WriteString("\\textbf{Checks} & \\textbf{Pairs} & \\textbf{Flipped} & \\textbf{Unverified} & \\textbf{Window} \\\\\n\\midrule\n")

	windowCell := func(changed, pairs int) string {
		if r.WindowDetail == nil || pairs == 0 {
			return na
		}
		return fmt.Sprintf("%d/%d", changed, pairs)
	}
	flipCell := func(flipped, pairs int) string {
		if pairs == 0 {
			return na
		}
		return strconv.Itoa(flipped)
	}
	rows := tableRows(r.Checks)
	if len(rows) == 0 {
		fmt.Fprintf(&sb, "\\multicolumn{5}{l}{%s} \\\\\n", na)
	}
	for _, row := range rows {
		fmt.Fprintf(&sb, "%s & %d & %s & %d & %s \\\\\n", row.label, row.pairs, flipCell(row.flipped, row.pairs), row.unverified, windowCell(row.windowChanged, row.windowPairs))
	}
	sb.WriteString("\\midrule\n")
	windowTotal := na
	if r.WindowDetail != nil {
		windowTotal = windowCell(r.WindowDetail.Changed, r.WindowDetail.Pairs)
	}
	fmt.Fprintf(&sb, "All checks & %d & %s & %d & %s \\\\\n", r.Pairs, flipCell(r.FlippedChecks, r.Pairs), r.PairsUnverifiedInSomeRepeat, windowTotal)
	sb.WriteString("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
	return sb.String()
}

// WriteJSON writes reliability.json.
func WriteJSON(dir string, r *Report) error {
	data, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return err
	}
	return writeAtomic(filepath.Join(dir, jsonFile), append(data, '\n'))
}

// writeAtomic writes a file through a temporary file in the same directory.
func writeAtomic(path string, data []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".tmp-"+filepath.Base(path)+"-")
	if err != nil {
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		os.Remove(tmp.Name())
		return err
	}
	if err := tmp.Close(); err != nil {
		os.Remove(tmp.Name())
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		os.Remove(tmp.Name())
		return err
	}
	return os.Rename(tmp.Name(), path)
}

// WriteAll writes the JSON file, the table and the macros into dir.
func WriteAll(dir string, r *Report) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	if err := WriteJSON(dir, r); err != nil {
		return err
	}
	if err := writeAtomic(filepath.Join(dir, tableFile), []byte(RenderTable(r))); err != nil {
		return err
	}
	return writeAtomic(filepath.Join(dir, macrosFile), []byte(RenderMacros(r)))
}
