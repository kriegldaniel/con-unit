// tableLabel is the label of the table, which belongs to the supplement.
const tableLabel = "tab:attribution"

// macro is one generated command with the comment that defines it.
type macro struct {
	name    string
	value   string
	comment string
}

func count(n int) string { return strconv.Itoa(n) }

// attributionMacros returns the macros of the attribution and the ablation in
// the order of docs/INTERFACE_V2.md section 6. A block that is missing prints
// n/a. att and abl may be nil.
func attributionMacros(att *Document, abl *AblationDocument) []macro {
	na := tex.NotAvailable
	seeded := func(get func(SeededSummary) int) string {
		if att == nil || att.Seeded == nil {
			return na
		}
		return count(get(att.Seeded.Summary))
	}
	real := func(get func(RuleSummary) int) string {
		if !att.HasStudy() {
			return na
		}
		return count(get(att.Summary.Total))
	}
	ablated := func(get func(AblationSummary) int) string {
		if abl == nil {
			return na
		}
		return count(get(abl.Summary))
	}
	return []macro{
		{"ConUnitAttrSeededN", seeded(func(s SeededSummary) int { return s.N }),
			"Seeded cases in the accuracy denominator: those with a verdict EXACT, SUPERSET or WRONG. Cases that do not manifest on the engine are not counted."},
		{"ConUnitAttrSeededExact", seeded(func(s SeededSummary) int { return s.Exact }),
			"Seeded cases whose minimal set equals the expected set."},
		{"ConUnitAttrSeededSuperset", seeded(func(s SeededSummary) int { return s.Superset }),
			"Seeded cases whose minimal set holds every expected element and at least one more."},
		{"ConUnitAttrSeededWrong", seeded(func(s SeededSummary) int { return s.Wrong }),
			"Seeded cases attributed to another cause, left unresolved, or resolved without a minimal set."},
		{"ConUnitAttrSeededNotManifested", seeded(func(s SeededSummary) int { return s.NotManifested }),
			"Seeded cases that the truth file records as not manifesting on the engine. Reported and not scored. This macro is not in docs/INTERFACE_V2.md."},
		{"ConUnitAttrRealPairs", real(func(s RuleSummary) int { return s.Examined }),
			"Image and rule pairs with an EXEC-01 or EXEC-02 FAIL in the study."},
		{"ConUnitAttrRealReproducible", real(func(s RuleSummary) int { return s.Attributable }),
			"Pairs whose failure reproduced with a baseline that stayed running."},
		{"ConUnitAttrRealNamedSingle", real(func(s RuleSummary) int { return s.ResolvedBySingle }),
			"Reproducible pairs that one added capability or mount resolves alone."},
		{"ConUnitAttrRealNamedMinimal", real(func(s RuleSummary) int { return s.ResolvedByMinimal }),
			"Reproducible pairs that no single candidate resolves and a minimal set of candidates found by minimization does."},
		{"ConUnitAttrRealUnionOnly", real(func(s RuleSummary) int { return s.ResolvedByUnionOnly }),
			"Reproducible pairs that only the union of all candidates resolves and that were not shrunk."},
		{"ConUnitAttrRealUnresolved", real(func(s RuleSummary) int { return s.Unresolved }),
			"Reproducible pairs that not even the union of all candidates resolves."},
		{"ConUnitAblExamined", ablated(func(s AblationSummary) int { return s.ImagesExamined }),
			"Images with a Tier 3 result that is UNVERIFIED with BASELINE_FAILED or NOT_OBSERVABLE, for which all four treatments were observed without the baseline gate."},
		{"ConUnitAblMisblamed", ablated(func(s AblationSummary) int { return s.ImagesMisblamed }),
			"Examined images for which a single-run tool, with no baseline gate, would have called FAIL for at least one of the four treatments."},
	}
}

// RenderMacros renders macros_attribution.tex. Every macro name contains
// letters only, and every value is a count.
func RenderMacros(att *Document, abl *AblationDocument) string {
	var sb strings.Builder
	sb.WriteString("% Generated by tools/attribute_exec from attribution.json and ablation.json. Do not edit by hand.\n")
	sb.WriteString("% Macro names contain letters only. Every value is a count of images, image and rule pairs or seeded cases, without a unit.\n")
	sb.WriteString("% A value for which no data exists prints n/a.\n")
	if att.HasStudy() && !att.Complete {
		sb.WriteString("% WARNING: the study block of attribution.json is incomplete.\n")
	}
	if att != nil && att.Seeded != nil && !att.Seeded.Complete {
		sb.WriteString("% WARNING: the seeded block of attribution.json is incomplete.\n")
	}
	if abl != nil && !abl.Complete {
		sb.WriteString("% WARNING: ablation.json is incomplete.\n")
	}
	for _, m := range attributionMacros(att, abl) {
		fmt.Fprintf(&sb, "\n%% %s\n\\newcommand{\\%s}{%s}\n", m.comment, m.name, m.value)
	}
	return sb.String()
}

// tableCaption describes the table without any number, so that the figures of
// the text come from the macros.
const tableCaption = "Attribution of Tier 3 failures by controlled re-runs under the defensive profile. " +
	"Seeded cases: each seeded image is re-run with the capabilities or mounts added back and the minimal set that keeps it alive is compared with the intended cause. " +
	"Cases that do not manifest on this engine are listed and not scored. " +
	"Real failures: the EXEC-01 and EXEC-02 FAIL results of the study, attributed the same way. " +
	"Ablation: the images whose Tier 3 results are UNVERIFIED because the baseline failed or exited early, re-run without the baseline gate, as a tool with a single run would do."

// RenderTable renders table_attribution.tex with the label tab:attribution.
func RenderTable(att *Document, abl *AblationDocument) string {
	var sb strings.Builder
	row := func(label string, value string) {
		fmt.Fprintf(&sb, "\\multicolumn{4}{@{}l}{%s} & %s \\\\\n", label, value)
	}
	section := func(title string) {
		fmt.Fprintf(&sb, "\\multicolumn{5}{@{}l}{\\textbf{%s}} \\\\\n\\midrule\n", title)
	}
	none := func() { sb.WriteString("\\multicolumn{5}{@{}l}{" + tex.NotAvailable + "} \\\\\n") }

	sb.WriteString("% Generated by tools/attribute_exec from attribution.json and ablation.json. Do not edit by hand.\n")
	sb.WriteString("\\begin{table*}[t]\n\\centering\n\\small\n")
	fmt.Fprintf(&sb, "\\caption{%s}\n\\label{%s}\n", tableCaption, tableLabel)
	sb.WriteString("\\begin{tabular}{@{}lllll@{}}\n\\toprule\n")

	// Seeded cases.
	section("Seeded cases")
	if att == nil || att.Seeded == nil {
		none()
	} else {
		sb.WriteString("\\textit{Case} & \\textit{Rule} & \\textit{Expected} & \\textit{Found} & \\textit{Verdict} \\\\\n")
		for _, c := range att.Seeded.Cases {
			found := setLabel(c.MinimalSet)
			if found == "" {
				found = "none"
			}
			fmt.Fprintf(&sb, "%s & %s & %s & %s & %s \\\\\n", tex.Texttt(c.Case), tex.Escape(c.Rule),
				tex.Escape(setLabel(c.ExpectedMinimal)), tex.Escape(found), tex.Escape(strings.ReplaceAll(c.Verdict, "_", " ")))
		}
		s := att.Seeded.Summary
		row("Scored cases", count(s.N))
		row("\\quad exact", count(s.Exact))
		row("\\quad superset", count(s.Superset))
		row("\\quad wrong", count(s.Wrong))
		row("Not manifested on this engine, not scored", count(s.NotManifested))
		if s.Incomplete > 0 {
			row("Without a verdict, the run was incomplete", count(s.Incomplete))
		}
	}

	// Real failures.
	sb.WriteString("\\midrule\n")
	section("Real failures of the study")
	if !att.HasStudy() {
		none()
	} else {
		t := att.Summary.Total
		row("Image and rule pairs with a FAIL", count(t.Examined))
		row("Failure reproduced with a running baseline", count(t.Attributable))
		row("\\quad resolved by one capability or mount", count(t.ResolvedBySingle))
		row("\\quad resolved by a minimal set of several", count(t.ResolvedByMinimal))
		row("\\quad resolved by the union of all candidates only", count(t.ResolvedByUnionOnly))
		row("\\quad unresolved", count(t.Unresolved))
		row("Failure did not reproduce", count(t.NotReproduced))
		row("Baseline failed", count(t.BaselineFailed))
		row("Baseline exited early", count(t.NotObservable))
		row("Image absent or engine error", count(t.ImageAbsent+t.Error))
		for _, set := range minimalSetsByCount(att.Summary) {
			row("\\quad set "+tex.Texttt(set.label), count(set.n))
		}
	}

	// Ablation.
	sb.WriteString("\\midrule\n")
	section("Ablation without the baseline gate")
	if abl == nil {
		none()
	} else {
		s := abl.Summary
		row("Images with Tier 3 UNVERIFIED, all four treatments observed", count(s.ImagesExamined))
		row("\\quad a single-run tool would call FAIL for at least one treatment", count(s.ImagesMisblamed))
		for _, reason := range sortedKeys(s.ByStudyReason) {
			rs := s.ByStudyReason[reason]
			row("\\quad "+tex.Texttt(reason)+", examined and FAIL", fmt.Sprintf("%d and %d", rs.Examined, rs.Misblamed))
		}
		row("Treatment runs observed", count(s.PairsExamined))
		row("\\quad a single-run tool would call FAIL", count(s.PairsFail))
		if s.ImagesAbsent+s.ImagesError > 0 {
			row("Images absent or with an engine error, not examined", count(s.ImagesAbsent+s.ImagesError))
		}
	}
	sb.WriteString("\\bottomrule\n\\end{tabular}\n\\end{table*}\n")
	return sb.String()
}

type setCount struct {
	label string
	n     int
}

// minimalSetsByCount lists the minimal sets of all rules, most frequent first,
// ties in name order.
func minimalSetsByCount(s Summary) []setCount {
	totals := map[string]int{}
	for _, rs := range s.ByRule {
		for set, n := range rs.ByMinimalSet {
			totals[set] += n
		}
	}
	out := make([]setCount, 0, len(totals))
	for set, n := range totals {
		out = append(out, setCount{set, n})
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].n != out[j].n {
			return out[i].n > out[j].n
		}
		return out[i].label < out[j].label
	})
	return out
}
